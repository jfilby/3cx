## Core domain types shared across the 3cx application.
##
## Nothing in this module depends on the terminal layer, which keeps the chat
## and session logic portable and straightforward to test.

type
  Role* = enum
    rUser,       ## A message typed by the human.
    rAssistant,  ## A message produced by the agent backend.
    rTool,       ## A tool call or its committed result.
    rSystem      ## Informational text generated by the UI or the harness.

  Message* = object
    role*: Role
    content*: string
    model*: string  ## Backend label that produced this message ("provider.model").
                    ##
                    ## Stamped when the message is opened rather than read from
                    ## the backend at paint time, because the transcript is
                    ## re-rendered every frame: a live lookup would repaint every
                    ## assistant message in the conversation with whichever model
                    ## is current *now*. Empty means "whatever the backend says",
                    ## which is what messages restored from a session file
                    ## written before this field existed get.

  Chat* = object
    messages*: seq[Message]

proc addMessage*(chat: var Chat, role: Role, content: string, model = "") =
  ## Append a message to the chat.
  chat.messages.add Message(role: role, content: content, model: model)

proc lastMessage*(chat: Chat): Message =
  ## The most recent message, or an empty system message if there are none.
  if chat.messages.len == 0:
    return Message(role: rSystem, content: "")
  chat.messages[^1]